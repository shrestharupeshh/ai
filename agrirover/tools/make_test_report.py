#!/usr/bin/env python3
"""Assemble docs/10_validation_test_report.md from the artefacts actually present in the repository.

Re-runs the firmware host tests and the Python test-suite (unless --no-run) so the numbers in the report are the
numbers of this checkout.
"""
import json
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def run(cmd, cwd):
    p = subprocess.run(cmd, cwd=cwd, capture_output=True, text=True)
    return p.returncode, (p.stdout + p.stderr).strip().splitlines()


def main():
    norun = "--no-run" in sys.argv
    sc = json.loads((ROOT / "sim/results/scenario_report.json").read_text())
    ref = json.loads((ROOT / "sim/results/reference/summary.json").read_text())
    drc = json.loads((ROOT / "electrical/pcb/reports/drc_summary.json").read_text())
    cad = json.loads((ROOT / "mechanical/export/cad_summary.json").read_text())
    schem = (ROOT / "electrical/pcb/reports/schematic_check.txt").read_text().strip().splitlines()
    fw = py = stm = "not re-run (--no-run)"
    if not norun:
        rc, out = run(["make", "test"], ROOT / "firmware")
        fw = f"{out[-1]} (exit {rc})"
        rc, out = run(["make", "stm32"], ROOT / "firmware")
        size = [l for l in out if "agrirover_fw.elf" in l and l.strip()[0].isdigit()]
        stm = f"links, exit {rc}" + (f"; text/data/bss = {'/'.join(size[-1].split()[:3])} bytes" if size else "")
        rc, out = run([sys.executable, "-m", "pytest", "-q"], ROOT / "software")
        py = f"{out[-1]} (exit {rc})"
    L = []
    a = L.append
    a("# 10 — Validation and test report\n")
    a("Generated by `tools/make_test_report.py` from the artefacts in this repository. Scope: what was checked while the "
      "design package was produced, with which tool, and what remains unverified. **No hardware exists yet: there are no "
      "physical test results in this document.** Simulation results describe the behaviour of the software in a simplified "
      "model and are not evidence of real-world performance.\n")
    a("## 1. Summary of executed checks\n")
    a("| Area | Check | Tool | Result |\n|---|---|---|---|")
    a("| Requirements ↔ design | calculations, CAD summary and software footprint agree with `config/rover.yaml` | pytest `test_design_is_consistent_with_requirements` | part of the Python suite below |")
    a(f"| Mechanical | assembly builds from parameters; pairwise interference check of {cad['n_parts']} placed parts | CadQuery / OpenCascade | {len(cad['interferences'])} interferences; envelope {cad['envelope_mm'][0]:.0f} × {cad['envelope_mm'][1]:.0f} × {cad['envelope_mm'][2]:.0f} mm |")
    a("| Mechanical | STEP assembly, part STEPs, STL, 3MF, DXF and drawings exported and re-readable | CadQuery exporters | files in `mechanical/export/` |")
    a(f"| Schematic | netlist extracted by KiCad equals design intent; pin-type and design rules | kicad-cli 7.0.11 + `check_netlist.py` | {schem[-2].replace('RESULT: ', '')} |")
    a(f"| PCB | design-rule check incl. clearance, shorts, connectivity | KiCad 7.0.11 DRC (`pcbnew.WriteDRCReport`) | {drc['drc']['unconnected pads']} unconnected pads; 0 clearance/short violations; warnings: " + ", ".join(f"{v} × {k}" for k, v in drc['by_type'].items()) + " |")
    a(f"| PCB | all nets routed | project maze router | {len(drc['unrouted'])} unrouted; {drc['tracks']} track segments, {drc['vias']} vias, {drc['track_len_mm']:.0f} mm |")
    a(f"| Firmware core | protocol, speed control, safety state machine against a simulated motor (ASan + UBSan) | gcc host build | {fw} |")
    a(f"| Firmware target | cross-compile for STM32F411 | arm-none-eabi-gcc 13.2 | {stm} |")
    a(f"| Software | unit, vision, scenario, dashboard-API and ROS-asset consistency tests | pytest | {py} |")
    a(f"| System (simulation) | {len(sc)} scenarios with acceptance criteria | headless simulator | {sum(s['passed'] for s in sc)} / {len(sc)} pass |")
    a("| ROS 2 workspace | URDF expands and loads; parameters, launch files and nodes parse; footprint, speeds and maps match the shared configuration | xacro, yourdfpy, PyYAML, `ast` | pass (static only) |")
    a("")
    a("## 2. Simulation scenarios\n")
    a("Model: kinematic differential drive with first-order wheel response, encoder/gyro/lidar noise, a facility in which "
      "only walls and bench legs are visible to the lidar, synthetic camera images shifted by the true stopping error, and a "
      "power model from the electrical calculations. Reduced greenhouse (2–3 benches of 4 m) for speed.\n")
    a("| Scenario | Purpose | Acceptance criteria (measured) | Result |\n|---|---|---|---|")
    for s in sc:
        crit = "<br>".join(f"{'✔' if c['ok'] else '✘'} {c['criterion']} ({c['measured']})" for c in s["criteria"])
        a(f"| `{s['name']}` | {s['purpose']} | {crit} | {'PASS' if s['passed'] else 'FAIL'} |")
    a("")
    a("### Reference mission (full reference greenhouse, 12 × 6.8 m, 3 benches, 32 stations, 384 plants)\n")
    a(f"State {ref['state']}; {ref['stations']} stations; {ref['distance_m']} m in {ref['duration_s']:.0f} s; {ref['energy_wh']} Wh "
      f"(analytic route model predicted {ref['predicted']['energy_wh']} Wh / {ref['predicted']['duration_s']:.0f} s); "
      f"{ref['collisions']} collisions; minimum clearance {ref['min_clearance_m']} m; stop error mean {ref['stop_error_mean_m']*1000:.0f} mm, "
      f"max {ref['stop_error_max_m']*1000:.0f} mm, {ref['stop_yaw_error_max_deg']}°; localisation error {ref['localisation_error_rms_m']*1000:.0f} mm RMS; "
      f"synthetic-truth flags: {ref['synthetic_truth']['true_positive']} true positive, {ref['synthetic_truth']['false_positive']} false positive, "
      f"{ref['synthetic_truth']['false_negative']} missed (mild-severity plants). Path and occupancy map: `sim/results/reference/`.\n")
    a("### What the scenarios changed in the design\n")
    a("Failures during development are recorded because they are the useful output of simulation:\n")
    a("* **Turning envelope.** A collision in the 0.60 m aisle showed that the bumper corners, not the deck corners, set the "
      "envelope (R 280 mm, not R 255 mm). The mechanical calculation, footprint model and requirement R-MOB-05 were corrected.")
    a("* **Benches are invisible to the lidar.** Reversing and turning are now checked against the facility map, aisles are "
      "entered through an aligned way-point, and a narrow aisle is left forwards rather than by a U-turn.")
    a("* **Rotation next to an unmapped obstacle** swept a corner into it; a turn-envelope check on the scan was added.")
    a("* **Localisation loss** was detected too slowly; scan matching now runs at 5 Hz and motion pauses on the first poor match.")
    a("* **Blur metric.** Variance-of-Laplacian tracked noise rather than sharpness; replaced by edge spread on the reference card.")
    a("* **Wall-side 0.60 m aisles** cannot be entered with a 20 mm turning margin; requirement R-ENV-03/04 was re-scoped instead of tuning the test.\n")
    a("### Limits of the simulation\n")
    a("No wheel slip dynamics, floor unevenness, caster shimmy or mast flex; lidar returns are ideal (no glass, sunlight, "
      "reflective film, foliage); people are static boxes; the localisation map equals the world; synthetic plants are flat "
      "coloured ellipses; the power model is the calculation it is compared with. Nav2 and Gazebo were **not** run.\n")
    a("## 3. Not verified\n")
    a("| Item | Why | What is needed |\n|---|---|---|")
    for row in [
        ("Any physical performance (speed, torque margin, runtime, stopping distance, stability)", "no hardware built", "tests T-MEC, T-PWR, T-SAF below"),
        ("ARC-1 electrical function", "board not fabricated; KiCad interactive ERC not run (no CLI ERC in KiCad 7)", "GUI ERC, peer review, bring-up table in docs/06"),
        ("Black Pill header order used on ARC-1", "written from memory, no primary source reachable", "compare with the physical module"),
        ("Footprints vs purchased parts (DPAK FET, fuse holder, connectors)", "stock KiCad footprints, parts not in hand", "1:1 print check"),
        ("STM32 firmware on a microcontroller", "cross-compiles only", "T-FW-01…03"),
        ("ROS 2 nodes, Nav2 configuration, Gazebo world", "ROS 2 / Gazebo could not be installed in the authoring environment (package repository blocked)", "`colcon build`, launch in Gazebo, repeat the scenarios (T-ROS)"),
        ("Hole patterns of purchased mechanical parts", "envelope models only", "measure parts before cutting plates"),
        ("Vision on real plants", "no real images; synthetic verification only", "docs/07 §5 workflow"),
        ("Sensor accuracy (T, RH, CO₂, light)", "datasheet values recalled, sensors not in hand", "comparison with reference instruments (T-SEN)"),
        ("Component prices and availability", "partly checked on the web, partly recalled", "re-quote at order time"),
        ("Ingress protection, EMC, battery/charger safety compliance", "not assessed", "outside revision A"),
    ]:
        a("| " + " | ".join(row) + " |")
    a("")
    a("## 4. Physical test plan (to be executed on the first build)\n")
    a("| ID | Test | Method | Acceptance criterion |\n|---|---|---|---|")
    for row in [
        ("T-FW-01", "Encoder counting", "rotate each wheel 10 turns by hand", "44 800 ± 20 counts, correct sign"),
        ("T-FW-02", "PWM, ADC, I²C timing", "logic analyser on J4, J8", "20 kHz PWM, duty matches command ±1 %, INA219/IMU read without NACK"),
        ("T-FW-03", "Speed loop", "wheels off the ground, step 0 → 6 rad/s", "settles within 0.5 s, overshoot < 10 %, steady-state error < 3 %"),
        ("T-MEC-01", "Mass and CG", "scale under each wheel/caster", "≤ 15 kg with payload; ≥ 80 % on the drive wheels"),
        ("T-MEC-02", "Speed and acceleration", "timed 5 m run, logged odometry", "0.5 m/s reached; 0.5 m/s² ± 20 %"),
        ("T-MEC-03", "Ramp", "5 % ramp, wet", "starts and holds without slip"),
        ("T-MEC-04", "Drivetrain durability", "20 h of missions", "no measurable shaft play; set screws tight"),
        ("T-MEC-05", "Tip stability", "tilt table", "≥ 20° in all directions at maximum mast height and payload"),
        ("T-MEC-06", "Mast settle time", "accelerometer or image blur after a stop", "edge spread ≤ 5 px after the configured settle time"),
        ("T-PWR-01", "State power", "INA219 log in idle / drive / turn / inspect", "within ±25 % of the budget; update the budget"),
        ("T-PWR-02", "Runtime", "repeat missions from 100 % to the 25 % return threshold", "≥ 4 h"),
        ("T-PWR-03", "Fault current", "stall both wheels", "current limited to ≤ 3 A per motor, fault trip in ≤ 2 s, F1 intact"),
        ("T-PWR-04", "Thermal", "thermocouples on Q1, Q2, drivers, regulator after 1 h", "< 40 K rise"),
        ("T-SAF-01", "E-stop function", "press while driving at 0.5 m/s, 10×", "stop ≤ 0.15 m; rail off ≤ 0.5 s; no restart without release + clear"),
        ("T-SAF-02", "Protective field", "cardboard target placed 0.3 m ahead at 0.3 and 0.5 m/s", "no contact; stop ≤ 0.15 m"),
        ("T-SAF-03", "Uncontrolled coast", "cut motor power at 0.5 m/s with the firmware stop disabled", "record the distance; if > 0.3 m, add dynamic braking in hardware"),
        ("T-SAF-04", "Link loss / watchdog", "unplug UART; halt the MCU with a debugger", "wheels stop ≤ 0.3 s; rail off ≤ 2 s / watchdog reset ≤ 0.3 s"),
        ("T-SAF-05", "Bumper contact force", "force gauge at 0.3 m/s against a rigid post", "record peak force; review against the intended use before working near people"),
        ("T-SAF-06", "Lidar failure", "unplug the lidar while driving", "stop within 0.5 s"),
        ("T-NAV-01", "Localisation", "compare with tape-measured floor marks at 10 stations", "≤ 0.05 m"),
        ("T-NAV-02", "Stop repeatability", "10 missions, measure stop positions against marks", "≤ 0.05 m, ≤ 3°"),
        ("T-NAV-03", "Narrow aisle", "0.60 m aisle between benches", "no contact in 10 passes"),
        ("T-NAV-04", "Obstacle handling", "crate in the corridor; cart blocking an aisle; person stepping out", "behaviours as in the simulated scenarios"),
        ("T-SEN-01", "Climate sensors", "side-by-side with calibrated references for 24 h", "within the R-SEN tolerances; else apply an offset"),
        ("T-ENV-01", "Drip resistance", "10 min vertical drip on the closed robot, powered", "no water inside the bay"),
        ("T-ROS-01", "ROS stack", "Gazebo: repeat nominal, obstacle and E-stop scenarios with Nav2", "same acceptance criteria as the headless scenarios"),
        ("T-CV-01", "Vision baseline", "labelled real images (docs/07 §5)", "report per-class precision/recall with confidence intervals — no threshold set in advance"),
    ]:
        a("| " + " | ".join(row) + " |")
    a("")
    a("## 5. Compatibility items to confirm on hardware\n")
    a("* Ubuntu 24.04 on the Raspberry Pi 5 with the chosen UART (`/dev/ttyAMA0`) and I²C-1 enabled; serial console disabled.")
    a("* `sllidar_ros2` with the RPLIDAR C1 at 460 800 baud under Jazzy.")
    a("* Two UVC cameras at 1280 × 720 on the Pi's USB controller simultaneously (bandwidth), with fixed focus/exposure controls honoured.")
    a("* Adafruit Blinka on Ubuntu 24.04 / Pi 5 for the three Qwiic sensors.")
    a("* Pi 5 powered through USB-C from a non-PD 5 V source with `usb_max_current_enable=1`.")
    (ROOT / "docs/10_validation_test_report.md").write_text("\n".join(L) + "\n")
    print("wrote docs/10_validation_test_report.md;", fw, "|", py)


if __name__ == "__main__":
    main()
