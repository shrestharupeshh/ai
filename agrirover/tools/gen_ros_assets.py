#!/usr/bin/env python3
"""Generate ROS / Gazebo assets from config/greenhouse.yaml (single source of truth for the facility):

  ros2_ws/src/agrirover_bringup/maps/greenhouse.pgm/.yaml     localisation map = what the 2D lidar sees (walls + bench legs)
  ros2_ws/src/agrirover_bringup/maps/keepout_mask.pgm/.yaml   Nav2 keep-out filter mask = bench footprints (invisible to the lidar)
  ros2_ws/src/agrirover_bringup/worlds/greenhouse.sdf         Gazebo (gz-sim 8 / Harmonic) world with benches, legs, plants, clutter
  ros2_ws/src/agrirover_bringup/config/stations.yaml          inspection stations and plant positions for the mission node
"""
import sys
from pathlib import Path

import cv2
import numpy as np
import yaml

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "software"))
from agrirover.sim.world import World  # noqa: E402

OUT = ROOT / "ros2_ws/src/agrirover_bringup"
RES, PAD = 0.05, 1.0


def to_px(x, y, h):
    return int(round((x + PAD) / RES)), h - 1 - int(round((y + PAD) / RES))


def main():
    w = World()
    W, H = int(round((w.w + 2 * PAD) / RES)), int(round((w.h + 2 * PAD) / RES))
    loc = np.full((H, W), 205, np.uint8)                                   # unknown outside
    cv2.rectangle(loc, to_px(0, 0, H), to_px(w.w, w.h, H), 254, -1)        # free inside
    cv2.rectangle(loc, to_px(0, 0, H), to_px(w.w, w.h, H), 0, 2)           # walls
    for leg in w.legs():
        cv2.rectangle(loc, to_px(leg.x0, leg.y0, H), to_px(leg.x1, leg.y1, H), 0, -1)
    keep = np.full((H, W), 254, np.uint8)                                  # 254 = free for the keepout filter
    for b in w.benches:
        cv2.rectangle(keep, to_px(b.x0, b.y0, H), to_px(b.x1, b.y1, H), 0, -1)
    (OUT / "maps").mkdir(parents=True, exist_ok=True)
    for name, img in (("greenhouse", loc), ("keepout_mask", keep)):
        cv2.imwrite(str(OUT / "maps" / f"{name}.pgm"), img)
        (OUT / "maps" / f"{name}.yaml").write_text(
            f"image: {name}.pgm\nmode: trinary\nresolution: {RES}\norigin: [{-PAD}, {-PAD}, 0.0]\nnegate: 0\noccupied_thresh: 0.65\nfree_thresh: 0.25\n")

    def box(name, x, y, z, sx, sy, sz, rgba, static=True):
        return f"""    <model name="{name}"><static>{str(static).lower()}</static><pose>{x:.3f} {y:.3f} {z:.3f} 0 0 0</pose>
      <link name="link"><collision name="c"><geometry><box><size>{sx:.3f} {sy:.3f} {sz:.3f}</size></box></geometry></collision>
        <visual name="v"><geometry><box><size>{sx:.3f} {sy:.3f} {sz:.3f}</size></box></geometry>
          <material><ambient>{rgba}</ambient><diffuse>{rgba}</diffuse></material></visual></link></model>\n"""

    b = w.cfg["bench"]
    m = []
    t = 0.1
    for name, x, y, sx, sy in (("wall_s", w.w / 2, -t / 2, w.w + 2 * t, t), ("wall_n", w.w / 2, w.h + t / 2, w.w + 2 * t, t),
                               ("wall_w", -t / 2, w.h / 2, t, w.h), ("wall_e", w.w + t / 2, w.h / 2, t, w.h)):
        m.append(box(name, x, y, 1.0, sx, sy, 2.0, "0.85 0.85 0.85 1"))
    for i, bx in enumerate(w.benches):
        m.append(box(f"bench{i+1}_top", (bx.x0 + bx.x1) / 2, (bx.y0 + bx.y1) / 2, b["top_z"] - 0.025, bx.x1 - bx.x0, bx.y1 - bx.y0, 0.05, "0.9 0.9 0.9 1"))
    for i, leg in enumerate(w.legs()):
        m.append(box(f"leg{i}", (leg.x0 + leg.x1) / 2, (leg.y0 + leg.y1) / 2, (b["top_z"] - 0.05) / 2, b["leg_size"], b["leg_size"], b["top_z"] - 0.05, "0.4 0.4 0.4 1"))
    for i, p in enumerate(w.plants.values()):                               # lettuce stand-ins: flat green cylinders
        m.append(f"""    <model name="plant{i}"><static>true</static><pose>{p['x']:.3f} {p['y']:.3f} {b['top_z'] + 0.03:.3f} 0 0 0</pose>
      <link name="link"><visual name="v"><geometry><cylinder><radius>0.09</radius><length>0.06</length></cylinder></geometry>
        <material><ambient>0.15 0.5 0.15 1</ambient><diffuse>0.2 0.65 0.2 1</diffuse></material></visual></link></model>\n""")
    for o in w.obstacles:
        m.append(box(o.name, (o.x0 + o.x1) / 2, (o.y0 + o.y1) / 2, 0.2, o.x1 - o.x0, o.y1 - o.y0, 0.4, "0.5 0.35 0.2 1"))
    sdf = f"""<?xml version="1.0"?>
<!-- Generated by tools/gen_ros_assets.py from config/greenhouse.yaml - do not edit by hand. -->
<sdf version="1.9">
  <world name="greenhouse">
    <physics name="1ms" type="ignored"><max_step_size>0.004</max_step_size><real_time_factor>1.0</real_time_factor></physics>
    <plugin filename="gz-sim-physics-system" name="gz::sim::systems::Physics"/>
    <plugin filename="gz-sim-user-commands-system" name="gz::sim::systems::UserCommands"/>
    <plugin filename="gz-sim-scene-broadcaster-system" name="gz::sim::systems::SceneBroadcaster"/>
    <plugin filename="gz-sim-sensors-system" name="gz::sim::systems::Sensors"><render_engine>ogre2</render_engine></plugin>
    <plugin filename="gz-sim-imu-system" name="gz::sim::systems::Imu"/>
    <light type="directional" name="sun"><cast_shadows>false</cast_shadows><pose>0 0 10 0 0 0</pose>
      <diffuse>0.9 0.9 0.9 1</diffuse><specular>0.2 0.2 0.2 1</specular><direction>-0.3 0.2 -0.9</direction></light>
    <model name="floor"><static>true</static><link name="link">
      <collision name="c"><geometry><plane><normal>0 0 1</normal><size>40 40</size></plane></geometry>
        <surface><friction><ode><mu>0.6</mu><mu2>0.6</mu2></ode></friction></surface></collision>
      <visual name="v"><geometry><plane><normal>0 0 1</normal><size>40 40</size></plane></geometry>
        <material><ambient>0.6 0.6 0.6 1</ambient><diffuse>0.6 0.6 0.6 1</diffuse></material></visual></link></model>
{''.join(m)}  </world>
</sdf>
"""
    (OUT / "worlds").mkdir(exist_ok=True)
    (OUT / "worlds" / "greenhouse.sdf").write_text(sdf)
    stations = dict(dock=dict(x=w.dock[0], y=w.dock[1], yaw=w.dock[2]),
                    stations=[dict(id=s.sid, x=s.x, y=s.y, aisle=s.aisle, views=s.views) for s in w.stations],
                    plants=w.plants, plants_per_row=w.cfg["plants"]["per_station"], rows=w.cfg["plants"]["rows_per_side"])
    (OUT / "config").mkdir(exist_ok=True)
    (OUT / "config" / "stations.yaml").write_text("# Generated by tools/gen_ros_assets.py\n" + yaml.safe_dump(stations, sort_keys=False, width=200))
    print(f"map {W}x{H} px, {len(w.legs())} legs, {len(w.plants)} plants, {len(w.stations)} stations")


if __name__ == "__main__":
    main()
