#!/usr/bin/env python3
"""Electrical calculations for AgriRover GH-1: power budget, runtime, currents,
fuse selection, PCB trace ampacity (IPC-2221), voltage drop and dissipation.

Writes electrical/calcs/electrical_calcs.md and electrical_results.json.
Analytical estimates only - nothing here has been measured.
"""
from __future__ import annotations

import json
import math
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[2]


def ipc2221_current(width_mm: float, dT: float, oz: float = 1.0, external: bool = True) -> float:
    area_mil2 = (width_mm / 0.0254) * (oz * 1.378)
    return (0.048 if external else 0.024) * dT ** 0.44 * area_mil2 ** 0.725


def ipc2221_dT(width_mm: float, amps: float, oz: float = 1.0) -> float:
    area_mil2 = (width_mm / 0.0254) * (oz * 1.378)
    return (amps / (0.048 * area_mil2 ** 0.725)) ** (1 / 0.44)


def trace_res(width_mm, length_mm, oz=1.0, temp=40.0):
    rho = 1.724e-8 * (1 + 0.00393 * (temp - 20))
    return rho * (length_mm / 1000) / ((width_mm / 1000) * (oz * 35e-6))


def main():
    cfg = yaml.safe_load((ROOT / "config/rover.yaml").read_text())
    mech = json.loads((ROOT / "mechanical/calcs/mechanical_results.json").read_text())
    pl, ba, mo, prof, rq = cfg["power_loads_w"], cfg["battery"], cfg["motor"], cfg["mission_profile"], cfg["requirements"]
    out, res = ["# AgriRover GH-1 — electrical calculations\n",
                "Generated by `electrical/calcs/electrical_calcs.py`. Estimates only; to be replaced by bench "
                "measurements (test T-PWR-01..04). Load figures marked *typ.* are typical values from vendor "
                "documentation or community measurements and are assumptions until measured."], {}
    p = out.append

    # ------------------------------------------------------------- power budget
    p("\n## 1. Power budget by operating state (at the battery, W)\n")
    eff = pl["dcdc_efficiency"]
    drive = mech["P_drive_cruise_W"] * 1.5      # +50 % for acceleration bursts, PWM and driver loss
    turn = mech["P_drive_turn_W"] * 1.5
    base = (pl["lidar"] + pl["cameras"] + pl["mcu_sensors"] + pl["wifi_extra"] + pl["leds_misc"]) / eff
    states = {
        "driving": pl["sbc_nav"] / eff + base + drive,
        "turning": pl["sbc_nav"] / eff + base + turn,
        "stopped_inspecting": (0.7 * pl["sbc_nav"] + 0.3 * pl["sbc_cv_peak"]) / eff + base,
        "idle": pl["sbc_idle"] / eff + base,
    }
    p("| State | Share of mission | Power [W] | Battery current @12.8 V [A] |\n|---|---:|---:|---:|")
    avg = 0.0
    for k, w in states.items():
        avg += prof[k] * w
        p(f"| {k} | {prof[k]*100:.0f} % | {w:.1f} | {w/ba['nominal_v']:.2f} |")
    p(f"| **mission average** | 100 % | **{avg:.1f}** | **{avg/ba['nominal_v']:.2f}** |")
    p(f"\nDrive power comes from the motor model in the mechanical calcs (cruise {mech['P_drive_cruise_W']:.1f} W, "
      f"turn {mech['P_drive_turn_W']:.1f} W) with a +50 % allowance. Motor current is **not** constant: "
      f"≈{mech['I_cruise_A']:.2f} A per motor at cruise, ≈{mech['I_peak_A']:.2f} A accelerating up the ramp, "
      f"up to the firmware limit of 3.0 A per motor in a stall, and {mo['stall_current_a']} A × "
      f"{ba['max_v']/12:.2f} = {mo['stall_current_a']*ba['max_v']/12:.1f} A hard stall at a full battery if the limit failed.")
    e_nom = ba["nominal_v"] * ba["capacity_ah"]
    usable = e_nom * (1 - rq["energy_reserve_frac"])
    rt = usable / avg
    p(f"\n## 2. Runtime\n\n    E_nominal = {ba['nominal_v']} V × {ba['capacity_ah']} Ah = {e_nom:.0f} Wh"
      f"\n    E_usable  = E_nominal × (1 − {rq['energy_reserve_frac']:.2f} reserve) = {usable:.0f} Wh"
      f"\n    runtime   = E_usable / P_avg = {usable:.0f} / {avg:.1f} = {rt:.1f} h   (requirement R-PWR-01: ≥ {rq['runtime_h']} h → "
      f"{'OK' if rt >= rq['runtime_h'] else 'NOT OK'})")
    worst = states["driving"] * 1.3
    p(f"\nPessimistic case (continuous driving, +30 %): {worst:.1f} W → {usable/worst:.1f} h. "
      "The 20 % reserve also protects LiFePO4 cycle life and covers the return-to-dock leg; the firmware "
      "raises LOW_BATTERY at 12.0 V resting (≈20 % SoC, flat LiFePO4 curve - coulomb counting from the INA219 "
      "is the primary SoC estimate) and CRITICAL at 11.2 V.")
    res.update(power_states_W=states, power_avg_W=avg, runtime_h=rt, usable_Wh=usable)

    # ------------------------------------------------------------- currents and fuses
    p("\n## 3. Branch currents and fuse selection\n")
    i_lim = 3.0
    i_sbc_max = 27.0 / eff / 11.0            # Pi 5 PSU budget 27 W at a low battery
    branches = [
        ("Motor rail (VMOT)", 2 * mech["I_cruise_A"], 2 * i_lim, "inside F1", "firmware current limit 3 A/motor; TB9051FTG chops at ~6.5 A typ."),
        ("SBC buck feed (VSBC)", (pl["sbc_nav"] + pl["lidar"] + pl["cameras"]) / eff / ba["nominal_v"], i_sbc_max, "F2 = 5 A", "Pi 5 + USB peripherals through the 5 V/5 A buck"),
        ("Aux feed (VAUX)", 0.0, 2.0, "F3 = 3 A", "spare: lighting / USB hub"),
        ("Logic 5 V (TSR 1-2450 input)", 0.8 / 0.9 / ba["nominal_v"], 1.0 * 5 / 0.9 / 10.0, "inside F1", "MCU, encoders, I2C sensors"),
    ]
    p("| Branch | Typical [A] | Worst case [A] | Protection | Note |\n|---|---:|---:|---|---|")
    tot_typ = tot_max = 0.0
    for n, t, m, f, note in branches:
        tot_typ += t
        tot_max += m
        p(f"| {n} | {t:.2f} | {m:.2f} | {f} | {note} |")
    p(f"| **Battery total** | **{tot_typ:.2f}** | **{tot_max:.2f}** | **F1 = 10 A** | battery BMS limit {ba['max_cont_discharge_a']:.0f} A (reseller figure) |")
    p(f"\n* F1 (10 A mini blade) carries the {tot_typ:.1f} A typical load at {tot_typ/10*100:.0f} % of its rating. "
      f"The arithmetic sum of every branch at its individual worst case is {tot_max:.1f} A ({tot_max/10*100:.0f} % of F1): "
      "both motors stalled at the firmware limit while the SBC draws its full 27 W budget and the aux output is fully "
      "loaded. That coincidence is treated as a fault - F1 is allowed to open (blade fuses carry 110 % indefinitely and "
      "open in minutes at 135 %, in ~0.1-5 s at 200 %). A hard short (pack can source > 20 A) is cleared before the "
      "2.5 mm traces overheat.")
    p("* Fuse coordination: F1 (10 A) > F2 (5 A) > F3 (3 A); wiring downstream of each fuse must be rated for the "
      "fuse, i.e. ≥ 18 AWG after F1/F2 and ≥ 20 AWG after F3 (chassis wiring, 80 °C PVC).")
    res.update(i_typ_A=tot_typ, i_worst_A=tot_max)

    # ------------------------------------------------------------- traces
    p("\n## 4. PCB trace ampacity (IPC-2221, external layers, 1 oz copper)\n")
    p("| Net class | Width [mm] | Design current [A] | ΔT at design current [°C] | Current for ΔT = 20 °C [A] |\n|---|---:|---:|---:|---:|")
    rows = [("Battery / motor path (hi)", 2.5, 6.0), ("VSBC", 2.0, 2.5), ("VAUX", 1.5, 2.0), ("+5V / +3V3", 0.6, 0.6),
            ("thin taps on hi nets", 0.4, 0.5), ("signal", 0.25, 0.05)]
    for n, w, i in rows:
        p(f"| {n} | {w} | {i} | {ipc2221_dT(w, i):.1f} | {ipc2221_current(w, 20):.1f} |")
    p(f"\nAt the 10 A fuse rating the 2.5 mm path would rise ≈{ipc2221_dT(2.5, 10):.0f} °C above ambient "
      "(steady state, no pour help): acceptable for a fault that the fuse clears, not as an operating point. "
      "If the design current grows beyond ~6 A continuous, order 2 oz copper (same Gerbers).")
    res["trace_dT_10A"] = ipc2221_dT(2.5, 10)

    # ------------------------------------------------------------- voltage drop / dissipation
    p("\n## 5. Voltage drop and dissipation in the power path\n")
    i = 6.0
    r_fuse, r_q, r_shunt, r_conn = 0.008, 0.015, 0.005, 0.003
    r_trace = trace_res(2.5, 90)
    parts = [("F1 10 A blade fuse (typ. cold resistance)", r_fuse), ("Q1 DMP4015SK3, Rds(on) at |Vgs| ≥ 10 V (max, hot)", r_q),
             ("R2 shunt 5 mΩ", r_shunt), ("Q2 DMP4015SK3", r_q), ("PCB track 2.5 mm × ~90 mm, 1 oz", r_trace),
             ("3 × connector contact", 3 * r_conn)]
    p(f"At I = {i} A (both motors at the firmware limit):\n\n| Element | R [mΩ] | V drop [mV] | P [W] |\n|---|---:|---:|---:|")
    vt = pt = 0
    for n, r in parts:
        vt += i * r
        pt += i * i * r
        p(f"| {n} | {r*1000:.1f} | {i*r*1000:.0f} | {i*i*r:.2f} |")
    p(f"| **Total** | {vt/i*1000:.1f} | **{vt*1000:.0f}** | **{pt:.2f}** |")
    p(f"\n* Drop is {vt/ba['nominal_v']*100:.1f} % of the nominal bus - negligible against the motor speed margin.")
    pq = i * i * r_q
    p(f"* Each DPAK P-FET dissipates {pq:.2f} W at {i} A; with ≈50 °C/W junction-to-ambient on a modest copper "
      f"area ΔT ≈ {pq*50:.0f} °C. Typical operation (≈1 A) is < 0.02 W. No heatsink required.")
    p(f"* Shunt: {i*i*r_shunt:.2f} W at {i} A, {100*r_shunt:.2f} W at 10 A, on a 2 W part. "
      f"INA219 shunt voltage at 10 A = {10*r_shunt*1000:.0f} mV → PGA ÷2 (±80 mV) range; LSB 10 µV ≙ 2 mA.")
    p("* Reverse battery: Q1's body diode blocks; the gate is clamped by D1. The TVS (D2) sits downstream of Q1 so it "
      "is never forward-biased by a reversed pack.")
    p("* 5 V logic rail: TSR 1-2450 (1 A, ~90 % efficient at 12 V in) supplies ≤ 0.35 A (MCU ≈ 50 mA, two encoders "
      "≈ 2 × 10 mA, AMS1117 load ≤ 250 mA peak during SCD41 measurement); LDO dissipation (5 − 3.3) V × 0.25 A = 0.43 W peak, "
      "≈ 0.1 W average on SOT-223.")
    res.update(vdrop_6A_mV=vt * 1000, p_loss_6A_W=pt)

    # ------------------------------------------------------------- connectors
    p("\n## 6. Connector and component ratings\n")
    p("| Item | Rating | Worst-case use | Margin |\n|---|---|---|---|")
    for row in [("Phoenix MSTBA 2,5/2-G-5,08 (J1, J5, J6, J7)", "12 A / 320 V (IEC)", "10 A (fuse-limited)", "1.2×"),
                ("Keystone 3568 mini blade holder", "30 A", "10 A", "3×"),
                ("JST XH (encoders, E-stop, UART, bumper)", "3 A / contact", "< 0.1 A", "> 30×"),
                ("JST SH Qwiic", "1 A / contact", "< 0.25 A", "4×"),
                ("DMP4015SK3 (Q1, Q2)", "-40 V, > 10 A continuous", f"{ba['max_v']} V, 10 A", "2.7× on voltage"),
                ("SMBJ16A TVS", "16 V stand-off, 26 V clamp", f"{ba['max_v']} V bus", "stand-off 1.1×"),
                ("INA219", "26 V bus max", f"{ba['max_v']} V", "1.8×"),
                ("C5 470 µF electrolytic", "25 V", f"{ba['max_v']} V", "1.7×"),
                ("TB9051FTG carrier (off-board)", "28 V, 2.6 A cont. / 5 A peak per channel", "≤ 3 A limited, typ. 0.4 A", "see note")]:
        p("| " + " | ".join(row) + " |")
    p("\nNote: the 3 A firmware limit is above the TB9051FTG carrier's 2.6 A continuous rating by design - it is a "
      "short-duration (< 2 s) stall limit followed by a fault trip; the driver's own thermal shutdown is the backstop.")
    p("\nThe Phoenix, Keystone and JST ratings above are quoted from memory of the manufacturer datasheets and must be "
      "re-checked against the current datasheets when the order is placed.")

    (ROOT / "electrical/calcs/electrical_calcs.md").write_text("\n".join(out) + "\n")
    (ROOT / "electrical/calcs/electrical_results.json").write_text(json.dumps(res, indent=2) + "\n")
    print(json.dumps(res, indent=2))


if __name__ == "__main__":
    main()
