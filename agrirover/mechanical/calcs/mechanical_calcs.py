#!/usr/bin/env python3
"""Mechanical sizing calculations for AgriRover GH-1.

Reads config/rover.yaml, prints every equation with numbers, and writes
  mechanical/calcs/mechanical_calcs.md   (human-readable report)
  mechanical/calcs/mechanical_results.json (consumed by tests / docs)

All results are ANALYTICAL ESTIMATES. Nothing here has been measured on
hardware. Assumed inputs are tagged (assumed) in rover.yaml.
"""
from __future__ import annotations

import json
import math
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[2]
G = 9.80665

# (x_mm from axle, z_mm above floor) of each mass_budget item, from the CAD layout.
POSITIONS = {
    "lower_plate": (0, 75), "upper_plate": (0, 178), "posts_and_brackets": (0, 127),
    "mast_assembly": (-150, 705), "motors": (0, 50), "motor_brackets": (0, 60),
    "wheels_adapters": (0, 50), "casters": (0, 35), "battery": (-45, 117),
    "sbc_and_storage": (95, 110), "control_pcb_mcu_drivers": (60, 105),
    "dcdc_and_wiring": (20, 100), "lidar": (150, 205),
    "cameras_and_mounts": (-150, 1230), "env_sensor_pod": (-150, 1150),
    "skirts_covers_bumper": (10, 125), "estop_switch_leds": (-200, 200),
    "fasteners": (0, 120),
}
PAYLOAD_POS = (0, 230)  # payload bay on the upper deck


def main() -> dict:
    cfg = yaml.safe_load((ROOT / "config/rover.yaml").read_text())
    rq, ch, mo, ba, tr = (cfg[k] for k in ("requirements", "chassis", "motor", "battery", "traction"))
    out: list[str] = []
    res: dict = {}

    def h(t):
        out.append(f"\n## {t}\n")

    def p(t=""):
        out.append(t)

    out.append("# AgriRover GH-1 — mechanical calculations\n")
    p("Generated by `mechanical/calcs/mechanical_calcs.py` from `config/rover.yaml`. "
      "Analytical estimates only; no value in this file has been measured on hardware.")

    # ---------------------------------------------------------------- mass / CG
    h("1. Mass budget and centre of gravity")
    mb = cfg["mass_budget_kg"]
    m_empty = sum(mb.values())
    m_pay = rq["payload_kg"]
    m = m_empty + m_pay
    sx = sum(mb[k] * POSITIONS[k][0] for k in mb) + m_pay * PAYLOAD_POS[0]
    sz = sum(mb[k] * POSITIONS[k][1] for k in mb) + m_pay * PAYLOAD_POS[1]
    xcg, zcg = sx / m / 1000, sz / m / 1000
    p("| Item | Mass [kg] | x [mm] | z [mm] |\n|---|---:|---:|---:|")
    for k, v in mb.items():
        p(f"| {k} | {v:.2f} | {POSITIONS[k][0]} | {POSITIONS[k][1]} |")
    p(f"| payload (max) | {m_pay:.2f} | {PAYLOAD_POS[0]} | {PAYLOAD_POS[1]} |")
    p(f"| **Total** | **{m:.2f}** | **{xcg*1000:.1f}** | **{zcg*1000:.1f}** |")
    p(f"\nEmpty mass {m_empty:.2f} kg; design mass with payload m = {m:.2f} kg "
      f"(limit R-MEC-04 = {rq['max_mass_kg']} kg, margin {rq['max_mass_kg']-m:.2f} kg).")
    p(f"CG: x = {xcg*1000:.1f} mm (negative = behind axle), z = {zcg*1000:.1f} mm.")
    res.update(mass_empty_kg=m_empty, mass_design_kg=m, cg_x_m=xcg, cg_z_m=zcg)

    # ---------------------------------------------------------------- wheel loads
    h("2. Wheel loading (static, level floor)")
    xc = ch["caster_x_mm"] / 1000
    W = m * G
    n_rear = W * (-xcg) / xc          # moment about the drive axle
    n_drive = W - n_rear
    p("The rover rests on the two drive wheels and the rear caster (front caster is "
      f"shimmed {ch['front_caster_gap_mm']} mm clear). Moments about the axle:")
    p(f"\n    N_rear = m g (-x_cg) / x_caster = {m:.2f}*{G:.2f}*{-xcg:.4f}/{xc:.3f} = {n_rear:.1f} N")
    p(f"    N_drive (both) = m g - N_rear = {n_drive:.1f} N  ->  {n_drive/2:.1f} N per wheel "
      f"({n_drive/W*100:.0f} % of weight on the driven wheels)")
    res.update(n_drive_total_N=n_drive, n_rear_caster_N=n_rear, drive_weight_frac=n_drive / W)
    assert n_rear > 0, "CG must be behind the axle so the rover rests on the rear caster"

    # ---------------------------------------------------------------- torque/speed
    h("3. Required wheel torque and speed")
    r = ch["wheel_diameter_mm"] / 2000
    v, a, crr, grade = rq["v_max"], rq["a_max"], tr["crr"], rq["ramp_grade"]
    theta = math.atan(grade)
    f_rr = crr * W * math.cos(theta)
    f_g = W * math.sin(theta)
    f_a = m * a
    f_cruise = f_rr
    f_peak = f_rr + f_g + f_a
    eta = tr["drivetrain_eff"]
    t_cruise = f_cruise * r / 2 / eta
    t_peak = f_peak * r / 2 / eta
    sf = 2.0
    w_wheel = v / r
    rpm = w_wheel * 60 / (2 * math.pi)
    p(f"Wheel radius r = {r*1000:.0f} mm, v_max = {v} m/s, a_max = {a} m/s², "
      f"C_rr = {crr}, grade = {grade*100:.0f} %, drivetrain efficiency = {eta}.")
    p(f"\n    F_roll  = C_rr m g cos(th) = {f_rr:.2f} N")
    p(f"    F_grade = m g sin(th)      = {f_g:.2f} N")
    p(f"    F_accel = m a              = {f_a:.2f} N")
    p(f"    F_peak  = sum              = {f_peak:.2f} N   (accelerating up the ramp)")
    p(f"    T_wheel,cruise = F_roll r / (2 eta)  = {t_cruise:.3f} N·m per wheel")
    p(f"    T_wheel,peak   = F_peak r / (2 eta)  = {t_peak:.3f} N·m per wheel")
    p(f"    with safety factor {sf:.0f}:            {t_peak*sf:.3f} N·m per wheel")
    p(f"    wheel speed at v_max = v / r = {w_wheel:.1f} rad/s = {rpm:.1f} rpm")
    res.update(F_peak_N=f_peak, T_cruise_Nm=t_cruise, T_peak_Nm=t_peak,
               T_peak_sf_Nm=t_peak * sf, wheel_rpm_vmax=rpm)

    h("4. Motor check — Pololu 4754 (70:1, 12 V)")
    ts, n0, i0, istall = mo["stall_torque_nm"], mo["no_load_rpm"], mo["no_load_current_a"], mo["stall_current_a"]
    p("Linear DC-motor model from the published 12 V points "
      f"(no-load {n0} rpm / {i0} A, stall {ts:.2f} N·m / {istall} A; stall values are "
      "extrapolated by the manufacturer). Speed scales with terminal voltage.")

    def op(torque, volts):
        n = n0 * volts / 12.0 * (1 - torque / (ts * volts / 12.0))
        i = i0 + (istall - i0) * torque / ts
        return n, i

    rows = []
    for label, tq in (("cruise", t_cruise), ("peak", t_peak), ("peak x SF2", t_peak * sf)):
        for volts in (12.0, ba["nominal_v"], 11.0):
            n, i = op(tq, volts)
            rows.append((label, tq, volts, n, n * 2 * math.pi / 60 * r, i))
    p("\n| Case | T [N·m] | V_motor [V] | speed [rpm] | v [m/s] | I [A] |\n|---|---:|---:|---:|---:|---:|")
    for row in rows:
        p("| {} | {:.3f} | {:.1f} | {:.0f} | {:.2f} | {:.2f} |".format(*row))
    n_pk, i_pk = op(t_peak, 11.0)
    v_pk = n_pk * 2 * math.pi / 60 * r
    n_cr, i_cr = op(t_cruise, ba["nominal_v"])
    p(f"\n* Speed margin: at the peak load and a sagging 11 V bus the motor still gives "
      f"{v_pk:.2f} m/s ≥ v_max = {v} m/s → {'OK' if v_pk >= v else 'NOT OK'}.")
    p(f"* Torque margin: stall/peak = {ts/t_peak:.1f}; gearbox continuous limit "
      f"{mo['max_cont_torque_nm']:.2f} N·m vs peak {t_peak:.2f} N·m → "
      f"ratio {mo['max_cont_torque_nm']/t_peak:.1f} (≥ 2 required) → "
      f"{'OK' if mo['max_cont_torque_nm']/t_peak >= 2 else 'NOT OK'}.")
    p(f"* Firmware speed limit is set to v_max; the motor is deliberately not run at its "
      f"no-load speed ({n0*2*math.pi/60*r:.2f} m/s at 12 V).")
    res.update(v_at_peak_11V=v_pk, I_cruise_A=i_cr, I_peak_A=i_pk,
               torque_margin_cont=mo["max_cont_torque_nm"] / t_peak)

    # ---------------------------------------------------------------- traction
    h("5. Traction")
    for name, mu in (("dry", tr["mu_dry"]), ("wet", tr["mu_wet"])):
        f_tr = mu * n_drive
        a_tr = (f_tr - f_rr) / m
        p(f"* {name}: F_traction,max = mu N_drive = {mu}*{n_drive:.1f} = {f_tr:.1f} N; "
          f"needed {f_peak:.1f} N → margin {f_tr/f_peak:.1f}x; traction-limited accel "
          f"{a_tr:.2f} m/s²; max climbable grade ≈ {math.degrees(math.atan(mu*n_drive/W - crr)):.0f}°.")
        res[f"traction_margin_{name}"] = f_tr / f_peak
    t_slip = tr["mu_dry"] * (n_drive / 2) * r
    p(f"* Wheel-slip torque on dry floor = mu (N_drive/2) r = {t_slip:.2f} N·m, below the "
      f"{ts:.2f} N·m stall torque, so a blocked rover spins its wheels or trips the firmware "
      "current limit rather than stalling the gearbox indefinitely (current limit still required).")

    # ---------------------------------------------------------------- braking
    h("6. Braking / stopping distance")
    a_brake = 1.5
    for name, lat in (("bumper / E-stop input (MCU loop)", 0.02), ("lidar protective field (10 Hz scan)", 0.12)):
        d = v * lat + v * v / (2 * a_brake)
        p(f"* {name}: latency {lat*1000:.0f} ms → d = v t + v²/(2a) = "
          f"{v}*{lat} + {v}²/(2*{a_brake}) = {d*1000:.0f} mm "
          f"({'meets' if d <= rq['stop_distance_m'] else 'exceeds'} R-SAF-02 = {rq['stop_distance_m']*1000:.0f} mm).")
        res[f"stop_dist_{'lidar' if lat > 0.05 else 'mcu'}_m"] = d
    mu_need = a_brake / G / (n_drive / W)
    p(f"* Controlled deceleration {a_brake} m/s² needs mu ≥ a/(g·drive fraction) = {mu_need:.2f} "
      f"(< wet value {tr['mu_wet']} → {'OK' if mu_need < tr['mu_wet'] else 'NOT OK'}).")
    t_brake = (m * a_brake - f_rr) * r / 2
    p(f"* Braking torque per wheel = {t_brake:.2f} N·m (< continuous gearbox limit).")
    p("* Uncontrolled coast after a hard motor-power cut depends on gearbox back-drive friction, "
      "which is **not published**; it must be measured (test T-SAF-03). The E-stop circuit therefore "
      "implements a controlled stop followed by a hardware-delayed power cut (see electrical docs).")
    # pitch-over during braking: front caster catches the rover.
    a_front = G * (xc - xcg) / zcg
    p(f"* Forward pitch-over about the front caster would need a = g (x_caster - x_cg)/z_cg = {a_front:.1f} m/s² "
      f"≫ {a_brake} m/s². The rover does rock onto the front caster (2 mm gap) when "
      f"a > g(-x_cg)/z_cg = {G*(-xcg)/zcg:.2f} m/s²; this is expected and bounded.")
    res.update(a_brake=a_brake, mu_needed_brake=mu_need)

    # ---------------------------------------------------------------- stability
    h("7. Static stability")
    half_track = ch["track_width_mm"] / 2000
    # support triangle: wheels (0, +-half_track), rear caster (-xc, 0)
    edge_len = math.hypot(xc, half_track)
    d_side = abs((xcg - 0) * (-half_track) - (0 - half_track) * (-xc)) / edge_len
    ang_side_tri = math.degrees(math.atan(d_side / zcg))
    ang_side_wheels = math.degrees(math.atan(half_track / zcg))
    ang_rear = math.degrees(math.atan((xc + xcg) / zcg))
    ang_front = math.degrees(math.atan((xc - xcg) / zcg))
    p(f"CG height {zcg*1000:.0f} mm, half track {half_track*1000:.0f} mm, caster arm {xc*1000:.0f} mm.")
    p(f"* Lateral tip angle over the wheel–rear-caster edge: atan({d_side*1000:.0f}/{zcg*1000:.0f}) = {ang_side_tri:.0f}°")
    p(f"* Lateral tip angle if the front caster also bears (diamond): up to {ang_side_wheels:.0f}° at the axle")
    p(f"* Rearward tip angle: {ang_rear:.0f}°   Forward tip angle (via front caster): {ang_front:.0f}°")
    a_lat = v * 1.0
    p(f"* Dynamic check: worst lateral acceleration v·ω = {v}×1.0 rad/s = {a_lat:.2f} m/s² "
      f"vs. tip threshold g·d/z = {G*d_side/zcg:.1f} m/s² → margin {G*d_side/zcg/a_lat:.0f}x.")
    res.update(tip_angle_lateral_deg=ang_side_tri, tip_angle_rear_deg=ang_rear)
    p("* Requirement R-SAF-05: static tip angle ≥ 20° in every direction → "
      f"{'OK' if min(ang_side_tri, ang_rear, ang_front) >= 20 else 'NOT OK'}.")

    # ---------------------------------------------------------------- geometry
    h("8. Envelope, clearance and turning")
    L, Wp, cham = ch["plate_length_mm"], ch["plate_width_mm"], ch["plate_corner_chamfer_mm"]
    width = ch["track_width_mm"] + ch["wheel_width_mm"]
    r_corner = max(math.hypot(L / 2, Wp / 2 - cham), math.hypot(L / 2 - cham, Wp / 2))
    r_wheel = math.hypot(width / 2, ch["wheel_diameter_mm"] / 2)
    r_bumper = L / 2 + 12  # bumper stands 12 mm proud of the plate at the nose
    r_swept = max(r_corner, r_wheel, r_bumper)
    clearance = ch["wheel_diameter_mm"] / 2 - 37 / 2
    p(f"* Overall width = track + wheel width = {width} mm (limit {rq['max_width_m']*1000:.0f}).")
    p(f"* Overall length = {L + 12} mm incl. bumper (limit {rq['max_length_m']*1000:.0f}).")
    p(f"* Overall height = camera mast top ≈ {ch['lower_plate_bottom_z_mm'] + 4 + ch['deck_post_len_mm'] + 3 + ch['mast_height_mm']} mm "
      f"(limit {rq['max_height_m']*1000:.0f}).")
    p(f"* Swept radius when turning in place = {r_swept:.0f} mm → swept diameter {2*r_swept:.0f} mm; "
      f"minimum turning radius of the path = 0 (differential drive, axle centred).")
    for aisle in (rq["aisle_min_transit_m"], rq["aisle_min_uturn_m"]):
        p(f"* Aisle {aisle*1000:.0f} mm: straight-line side clearance {(aisle*1000-width)/2:.0f} mm; "
          f"U-turn clearance {(aisle*1000-2*r_swept)/2:.0f} mm per side.")
    p(f"* Ground clearance = wheel radius − motor can radius = {ch['wheel_diameter_mm']/2:.0f} − 18.5 = "
      f"{clearance:.1f} mm (requirement ≥ {rq['ground_clearance_m']*1000:.0f} mm → "
      f"{'OK' if clearance >= rq['ground_clearance_m']*1000 else 'NOT OK'}).")
    res.update(overall_width_mm=width, swept_radius_mm=r_swept, ground_clearance_mm=clearance)

    # ---------------------------------------------------------------- structure
    h("9. Structural checks")
    E, sy = 70e9, 193e6  # 5052-H32
    b, t = L / 1000, ch["lower_plate_thk_mm"] / 1000
    span = 0.28
    F = (m - mb["motors"] - mb["wheels_adapters"] - mb["casters"] - mb["lower_plate"]) * G
    M = F * span / 4
    sig = 6 * M / (b * t * t)
    I = b * t ** 3 / 12
    defl = F * span ** 3 / (48 * E * I)
    p("**Lower plate** (5052-H32, 4 mm), conservatively modelled as a simply supported beam "
      f"spanning the two motor brackets ({span*1000:.0f} mm) with all supported mass as a centre point load:")
    p(f"\n    F = {F:.1f} N,  M = F L/4 = {M:.2f} N·m,  sigma = 6M/(b t²) = {sig/1e6:.1f} MPa "
      f"(yield {sy/1e6:.0f} MPa → SF {sy/sig:.0f}),  deflection = F L³/(48 E I) = {defl*1000:.2f} mm")
    res.update(plate_stress_MPa=sig / 1e6, plate_defl_mm=defl * 1000)

    d = mo["shaft_diameter_mm"] / 1000
    arm = 0.0275  # gearbox face to wheel centre plane
    shock = 2.5  # dynamic factor for thresholds / hose crossings
    Fw = n_drive / 2 * shock
    Ms = Fw * arm
    sig_s = 32 * Ms / (math.pi * d ** 3)
    p(f"\n**Motor output shaft** (Ø{d*1000:.0f} mm steel, wheel overhung {arm*1000:.0f} mm from the gearbox face, "
      f"dynamic factor {shock}):")
    p(f"\n    F = {Fw:.1f} N,  M = {Ms:.2f} N·m,  sigma_b = 32M/(pi d³) = {sig_s/1e6:.0f} MPa")
    p("\n  Bending stress is acceptable for shaft steel (yield typically > 400 MPa), but the **radial load rating of the 37D gearbox "
      "output bushing is not published by Pololu**. This is the main mechanical risk of the drivetrain; "
      "mitigation is an outboard pillow-block bearing (provision in the bracket hole pattern) if "
      "bushing wear is seen in test T-MEC-04.")
    res.update(shaft_stress_MPa=sig_s / 1e6)

    Lm = ch["mast_height_mm"] / 1000
    I_ext = 0.70e-8   # 2020 T-slot, typical Ix (m^4); check the supplier datasheet
    m_tip = mb["cameras_and_mounts"] + mb["env_sensor_pod"]
    m_beam = 0.45 * Lm
    F_tip = m_tip * G
    M_mast = F_tip * Lm + m_beam * G * Lm / 2
    sig_m = M_mast * 0.010 / I_ext
    k = 3 * E * I_ext / Lm ** 3
    fn = math.sqrt(k / (m_tip + 0.24 * m_beam)) / (2 * math.pi)
    d_tip = (m_tip * a_brake) / k
    p(f"\n**Camera mast** (2020 aluminium T-slot, cantilever {Lm*1000:.0f} mm, tip mass {m_tip:.2f} kg, "
      f"I ≈ {I_ext*1e8:.2f} cm⁴ typical):")
    p(f"\n    1 g lateral shock: M = {M_mast:.1f} N·m, sigma = {sig_m/1e6:.0f} MPa (6063-T5 yield ≈ 145 MPa)")
    p(f"    stiffness k = 3EI/L³ = {k:.0f} N/m; first bending mode ≈ {fn:.1f} Hz")
    p(f"    tip deflection during {a_brake} m/s² braking ≈ {d_tip*1000:.1f} mm")
    p(f"\n  A ~{fn:.0f} Hz mast mode means the camera rings after each stop; the mission planner "
      "waits `settle_time_s` (default 1.5 s) before capture and the image-quality gate rejects blurred frames.")
    res.update(mast_fn_hz=fn, mast_stress_MPa=sig_m / 1e6)

    # ---------------------------------------------------------------- energy
    h("10. Drive energy (feeds the electrical power budget)")
    Rm = mo["winding_resistance_ohm"]
    p_mech = f_rr * rq["v_inspect"]
    n_i, i_i = op(t_cruise, ba["nominal_v"])
    # electrical power per motor ~ back-EMF power + copper loss + no-load loss
    kt = ts / (istall - i0)
    p_el = 2 * ((i_i - i0) * kt * (rq["v_inspect"] / r) + i_i ** 2 * Rm + i0 * 12 * (rq["v_inspect"] / r) / (n0 * 2 * math.pi / 60))
    # turning in place at 0.8 rad/s: scrub of casters -> assume 2x rolling force per wheel
    t_turn = 2 * t_cruise
    i_t = i0 + (istall - i0) * t_turn / ts
    w_turn = 0.8 * half_track / r
    p_turn = 2 * ((i_t - i0) * kt * w_turn + i_t ** 2 * Rm + i0 * 12 * w_turn / (n0 * 2 * math.pi / 60))
    p(f"* Mechanical power at inspection speed {rq['v_inspect']} m/s: F_roll v = {p_mech:.2f} W.")
    p(f"* Motor current at cruise ≈ {i_i:.2f} A each; electrical drive power ≈ {p_el:.1f} W (both motors).")
    p(f"* Turn in place at 0.8 rad/s (caster scrub assumed to double wheel torque): ≈ {p_turn:.1f} W.")
    p("* Acceleration bursts and PWM/driver losses are covered by a +50 % allowance in the electrical budget.")
    res.update(P_drive_cruise_W=p_el, P_drive_turn_W=p_turn)

    (ROOT / "mechanical/calcs/mechanical_calcs.md").write_text("\n".join(out) + "\n")
    (ROOT / "mechanical/calcs/mechanical_results.json").write_text(json.dumps(res, indent=2) + "\n")
    return res


if __name__ == "__main__":
    r = main()
    print(json.dumps(r, indent=2))
